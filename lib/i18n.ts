/**
 * Traduz uma chave para o idioma informado, com substituição de variáveis
 * no formato {nome}. Usa pt-BR como fallback.
 */
export function translate(
  locale: Locale,
  key: StringKey,
  vars?: Record<string, string | number>,
): string {
  const dict = dictionaries[locale] ?? dictionaries[DEFAULT_LOCALE]
  let value = dict[key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replace(`{${name}}`, String(replacement))
    }
  }
  return value
}

/** Detecta o idioma do dispositivo, se suportado */
export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return DEFAULT_LOCALE
  const langs = navigator.languages ?? [navigator.language]
  for (const raw of langs) {
    const lower = raw.toLowerCase()
    if (lower.startsWith('pt')) return 'pt-BR'
    const base = lower.split('-')[0]
    const match = locales.find((l) => l.code === base)
    if (match) return match.code
  }
  return DEFAULT_LOCALE
}
